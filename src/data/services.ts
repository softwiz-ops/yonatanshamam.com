/**
 * The service catalogue.
 *
 * Rewritten from scratch on 27 Jul 2026. The previous version was built around
 * turnaround times and a scoping-then-draft process. The founder killed both:
 * "לא רוצה להציע שירותים מהירים כמו מפעל". He is right, and it also removes
 * every commitment that could not be approved — a promised turnaround is
 * exactly the kind of claim that misleads if it slips.
 *
 * WHAT REPLACED IT
 *
 * Depth. Each page answers the question a person actually typed into a search
 * box, in enough detail to be the last page they need to open. That is what
 * ranks, that is what a generative engine can quote, and it is the only
 * differentiator left once speed and price are both off the table.
 *
 * THE LINE THAT STILL HOLDS
 *
 * Everything here describes the LEGAL INSTRUMENT and the law around it —
 * general knowledge, accurate and defensible. Nothing describes how long this
 * firm takes, how many revisions it includes, or what it charges. Those are
 * commitments only the founder can make, and two of the three are forbidden
 * outright by the Bar's advertising rules.
 *
 * TWO QUALIFICATION LIMITS, CONFIRMED BY THE FOUNDER
 *
 * 1. He is NOT a notary — that needs ten years' standing and he was admitted in
 *    2019. So `affidavit` is scoped to affidavits and signature witnessing,
 *    which any lawyer may do, and the page says plainly when a notary IS
 *    required instead. Never let this page drift into offering notarial acts.
 * 2. He does NOT hold the Accountant General's certification for a lasting
 *    power of attorney (ייפוי כוח מתמשך), which only specifically trained
 *    lawyers may draw up. It is deliberately absent from this catalogue.
 */

