export interface Service {
  slug: string;
  title: string;
  /** Short label for cards, when the full title is long. */
  shortTitle?: string;
  category: Category;
  audience: Audience;
  tag?: string;
  tagAccent?: boolean;
  /** One sentence. Appears on cards and under the page title. */
  summary: string;
  seoTitle: string;
  seoDescription: string;
  primaryCta: { label: string; type: 'calendar' | 'whatsapp' };
  /**
   * Section headings, written per service rather than generic.
   *
   * The Israeli law-firm pages that rank first use literal, question-shaped
   * H2s that repeat the keyword — "מהו הסכם מייסדים ולמה הוא קריטי", "טעויות
   * נפוצות". Generic headings like "מה חשוב לדעת" carry no keyword and give a
   * generative engine nothing to match a question against.
   */
  headings: { intro: string; covers: string; watch: string };
  /** Substantive topical content. General legal knowledge, not a firm promise. */
  intro: string[];
  /** What the instrument itself regulates. */
  covers: { title: string; detail: string }[];
  /** What tends to go wrong without it. */
  whyItMatters: string;
  /** The mistakes people actually make. This is the section that gets quoted. */
  watchFor: { title: string; detail: string }[];
  faqs: { q: string; a: string }[];
}

