export interface Service {
  slug: string;
  title: string;
  /** Short label for cards and navigation, when the full title is long. */
  shortTitle?: string;
  category: Category;
  tag?: string;
  /** Whether the tag gets the accent treatment. */
  tagAccent?: boolean;
  /** The founder's own copy, verbatim from the live site. */
  summary: string;
  /** Page title and meta description. Hand-written, never templated. */
  seoTitle: string;
  seoDescription: string;
  /** Primary conversion route. Property work opens with a meeting, not a chat. */
  primaryCta: { label: string; type: 'calendar' | 'whatsapp' };
  /** Substantive topical content. General legal knowledge, not a firm promise. */
  intro: string[];
  /** What the instrument itself regulates. */
  covers: { title: string; detail: string }[];
  /** What tends to go wrong without it. */
  whyItMatters: string;
  faqs: { q: string; a: string }[];
  /**
   * Firm commitments. Null until the founder supplies them — see the note at
   * the top of this file.
   */
  scope: null | { included: string[]; excluded: string[] };
  timeline: null | string;
}

