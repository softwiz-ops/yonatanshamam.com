/**
 * The nine services.
 *
 * There is a hard line running through every entry here, and it is the reason
 * the shape looks the way it does:
 *
 *   `summary`, `intro`, `covers`, `whyItMatters` and `faqs` describe the LEGAL
 *   INSTRUMENT — what a founders agreement regulates, what the Companies
 *   Registrar requires, what Regulation 35 demands. That is general legal
 *   knowledge. It is accurate, defensible, and it is what actually ranks.
 *
 *   `scope` and `timeline` would be COMMITMENTS BY THIS FIRM — how many
 *   revision rounds are included, how long a draft takes, what falls outside
 *   the engagement. Those are factual claims about this practice. Only the
 *   founder can make them, and under the Bar's rules advertising must not
 *   mislead. They stay null until he supplies them, and render as a visible
 *   [[חסר]] marker.
 *
 * Copying a competitor's "up to 3 revision rounds" into this file would invent
 * an obligation the founder never agreed to. Do not do it.
 *
 * `summary` is the founder's own wording from the live site, verbatim. Correct
 * only punctuation and spelling; do not rewrite his phrasing.
 *
 * No fee information appears anywhere, at any level. That is not an oversight.
 */

